#!/usr/bin/env bash
# Run terraform fmt / init / validate / plan for one environment WITHOUT AWS credentials or a real state bucket.
#
#   ./scripts/tf-plan-offline.sh dev
#   ./scripts/tf-plan-offline.sh prod
#
# How it works: a temporary *_override.tf file switches the S3 backend to local state and gives the AWS
# provider mock credentials with every account/STS lookup skipped. With -refresh=false and no data sources
# that call AWS APIs, plan makes no network calls to AWS. The override file is removed on exit, so the
# committed backend.tf / providers.tf are never modified.
#
# With real credentials, skip this script and run the normal workflow in infra/envs/<env>:
#   terraform init && terraform plan -refresh=false
set -euo pipefail

ENV="${1:-}"
if [[ "$ENV" != "dev" && "$ENV" != "prod" ]]; then
  echo "usage: $0 <dev|prod>" >&2
  exit 2
fi

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_DIR="$ROOT/infra/envs/$ENV"
OVERRIDE="$ENV_DIR/zz_offline_override.tf"
OUT_DIR="$ROOT/plans"
mkdir -p "$OUT_DIR"

# Keep offline init data apart from a real 'terraform init' in the same folder.
export TF_DATA_DIR="$ENV_DIR/.terraform-offline"
export TF_IN_AUTOMATION=1

cleanup() { rm -f "$OVERRIDE"; }
trap cleanup EXIT

cat >"$OVERRIDE" <<EOF
# GENERATED by scripts/tf-plan-offline.sh - removed automatically, never commit.
terraform {
  backend "local" {
    path = "$TF_DATA_DIR/terraform.tfstate"
  }
}

provider "aws" {
  region                      = var.region
  access_key                  = "mock_access_key"
  secret_key                  = "mock_secret_key"
  skip_credentials_validation = true
  skip_requesting_account_id  = true
  skip_metadata_api_check     = true
  skip_region_validation      = true
}
EOF

cd "$ENV_DIR"

echo "==> [$ENV] terraform fmt -check -recursive (whole infra/ tree)"
terraform -chdir="$ROOT/infra" fmt -check -recursive -diff

echo "==> [$ENV] terraform init (local backend, offline override)"
terraform init -input=false -reconfigure -no-color >/dev/null

echo "==> [$ENV] terraform validate"
terraform validate -no-color

echo "==> [$ENV] terraform plan -refresh=false"
terraform plan -input=false -refresh=false -lock=false -no-color -out="$OUT_DIR/$ENV.tfplan" | tee "$OUT_DIR/$ENV.plan.txt"

echo
echo "Plan saved: plans/$ENV.tfplan (binary) and plans/$ENV.plan.txt (readable)"
